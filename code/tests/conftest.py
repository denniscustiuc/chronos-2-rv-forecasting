TRUE_HAR_COEFFICIENTS = (0.0100, 0.35, 0.35, 0.25)  # intercept, daily, weekly, monthly


def simulate_har(
    coefficients: tuple[float, float, float, float] = TRUE_HAR_COEFFICIENTS,
    n_days: int = 3000,
    sigma: float = 0.010,
    *,
    in_logs: bool = False,
    seed: int = 17,
    start: str = "2010-01-04",
) -> pd.Series:
    """Simulate a series generated by a known one-step HAR process.

    Mirrors exactly the recursion :mod:`volmodels.har` estimates: the value at
    ``t+1`` is a linear function of the daily, weekly (5-day) and monthly
    (22-day) trailing averages ending at ``t``, plus Gaussian noise.  Estimating
    HAR on the output must therefore recover ``coefficients``.

    Args:
        coefficients: ``(intercept, beta_daily, beta_weekly, beta_monthly)``.
            The three betas should sum below 1 for stationarity.
        n_days: Length of the series.
        sigma: Innovation standard deviation.
        in_logs: Run the recursion in log space and exponentiate the result, so
            that ``LogHAR`` rather than ``HAR`` is the correctly-specified model.
        seed: RNG seed.
        start: First date of the business-day index.

    Returns:
        A strictly positive volatility series indexed by business day.
    """
    intercept, b_daily, b_weekly, b_monthly = coefficients
    rng = np.random.default_rng(seed)

    level = intercept / max(1e-6, 1.0 - (b_daily + b_weekly + b_monthly))
    values = np.full(n_days, level, dtype="float64")
    values[:22] += rng.normal(0.0, sigma, size=22)

    for t in range(21, n_days - 1):
        daily = values[t]
        weekly = values[t - 4 : t + 1].mean()
        monthly = values[t - 21 : t + 1].mean()
        values[t + 1] = (
            intercept
            + b_daily * daily
            + b_weekly * weekly
            + b_monthly * monthly
            + rng.normal(0.0, sigma)
        )

    series = pd.Series(
        values, index=pd.bdate_range(start=start, periods=n_days, name="date"), name="rv"
    )
    if in_logs:
        return np.exp(series)
    # Keep the levels-space series strictly positive without distorting its
    # dynamics: the simulation only dips near zero when sigma is large.
    return series.clip(lower=1e-4)


@pytest.fixture(scope="session")
def har_series() -> pd.Series:
    """Levels-space series generated by a known HAR process."""
    return simulate_har()


@pytest.fixture(scope="session")
def log_har_series() -> pd.Series:
    """Series whose *logarithm* follows a known HAR process."""
    return simulate_har(
        coefficients=(-0.0805, 0.35, 0.35, 0.25), sigma=0.10, in_logs=True, seed=29
    )


@pytest.fixture(scope="session")
def rv_series() -> pd.Series:
    """A short, realistic-looking RV series for harness tests."""
    return simulate_har(n_days=600, seed=5)
